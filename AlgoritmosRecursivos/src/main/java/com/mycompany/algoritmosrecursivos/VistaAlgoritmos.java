    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        
    String algoritmo = jComboBox1.getSelectedItem().toString();

    try {

        
        if (algoritmo.equals("Primos")) {

        jLabel2.setText("Numero:");    
        int n = Integer.parseInt(jTextField1.getText());

        if (n < 2) {
        jLabel4.setText("No hay números primos.");
        return;
        }

        jLabel4.setText(Primos.VerPrimos(1, n));


        } else if (algoritmo.equals("Binarios")) {

            jLabel2.setText("Numero:"); 
            int numero = Integer.parseInt(jTextField1.getText());

            if (numero < 0) {
                jLabel4.setText("Introduce un número positivo.");
                return;
            }

            String resultado = Binarios.decimalBinario(numero);

            jLabel4.setText(resultado);


        } else if (algoritmo.equals("fibonacci")) {

            jLabel2.setText("Numero:"); 
            int cantidad = Integer.parseInt(jTextField1.getText());

            if (cantidad <= 0) {
                jLabel4.setText("Introduce una cantidad mayor que 0.");
                return;
            }

            jLabel4.setText(Fibonacci.mostrarSerie(cantidad, 0));

            
        } else if (algoritmo.equals("Rectangulo")) {

            int ancho = Integer.parseInt(jTextField1.getText());
            int alto = Integer.parseInt(jTextField2.getText());

            if (ancho <= 0 || alto <= 0) {
                jLabel4.setText("Las dimensiones deben ser mayores que 0.");
                return;
            }

            VentanaRectangulo ventana =
                    new VentanaRectangulo(ancho, alto);

            ventana.setVisible(true);

            jLabel4.setText("Rectángulo creado.");

        }

    } catch (NumberFormatException e) {

        jLabel4.setText("Introduce solamente números.");
    }
    }//GEN-LAST:event_jButton1ActionPerformed

